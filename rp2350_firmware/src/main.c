static inline float _rad2deg(float rad)
{
    return rad * (180.0f / 3.14159265358979323846f);
}

/**
 * @brief  Print per-sensor 3D points + centroid, and return the centroid.
 *
 * @param pts   array of @p n solved points
 * @param n     number of points
 * @param cx,cy,cz  out: centroid (averaged over per-sensor means)
 * @return      number of active sensors contributing to the centroid (0 = none)
 */
static int _print_and_centroid(const lh2_point3d_t *pts, int n,
                               float *cx, float *cy, float *cz)
{
    if (n <= 0) return 0;

    float sensor_x[NUM_SENSORS] = {0};
    float sensor_y[NUM_SENSORS] = {0};
    float sensor_z[NUM_SENSORS] = {0};
    int   sensor_cnt[NUM_SENSORS] = {0};

    for (int i = 0; i < n; i++) {
        int s = pts[i].sensor_id;
        if (s >= 0 && s < NUM_SENSORS) {
            sensor_x[s] += pts[i].xyz[0];
            sensor_y[s] += pts[i].xyz[1];
            sensor_z[s] += pts[i].xyz[2];
            sensor_cnt[s]++;
        }
    }

    float sum_x = 0.0f, sum_y = 0.0f, sum_z = 0.0f;
    int   n_active = 0;

    for (int s = 0; s < NUM_SENSORS; s++) {
        if (sensor_cnt[s] == 0) continue;
        float x = sensor_x[s] / sensor_cnt[s];
        float y = sensor_y[s] / sensor_cnt[s];
        float z = sensor_z[s] / sensor_cnt[s];
        printf("P,%d,%.4f,%.4f,%.4f\n", s, (double)x, (double)y, (double)z);
        sum_x += x; sum_y += y; sum_z += z;
        n_active++;
    }

    if (n_active == 0) return 0;

    *cx = sum_x / n_active;
    *cy = sum_y / n_active;
    *cz = sum_z / n_active;
    printf("C,%d,%.4f,%.4f,%.4f\n", n_active,
           (double)*cx, (double)*cy, (double)*cz);
    return n_active;
}

// ---------------------------------------------------------------------------
// Core 0 — main()
// ---------------------------------------------------------------------------

int main(void)
{
    /* ① Clock + peripherals */
    set_sys_clock_khz(128000, true);
    stdio_init_all();
    printf("DBG1: stdio initialized\n");
    stdio_flush();
    printf("BOOT: LH2 firmware started\n");
    stdio_flush();
    const uint32_t mav_baud = mavlink_init();   /* UART0 GPIO 0/1 → Pixhawk TELEM2 */
    printf("DBG2: MAVLink initialized at %lu baud (flight controller: SERIALx_BAUD = %lu)\n",
           (unsigned long)mav_baud, (unsigned long)((mav_baud + 500u) / 1000u));
    stdio_flush();
    mavlink_request_ekf_stream();  /* ask FC to stream EKF_STATUS_REPORT @ 1 Hz */
    printf("=== LH2 Crossing-Beams 3D Solver (dual-core) ===\n");
#ifdef SYNTHETIC_CAPTURE
    printf("Core 1: SYNTHETIC capture (no sensors, 1x1m square)\n");
#else
    printf("Core 1: capture (4 sensors)  Core 0: solve + MAVLink VPE\n");
#endif

    printf("BS poses: %s\n", BS_POSE_SOURCE);
    s_heading_cos = cosf(BS_WORLD_HEADING_DEG * (float)M_PI / 180.0f);
    s_heading_sin = sinf(BS_WORLD_HEADING_DEG * (float)M_PI / 180.0f);
    printf("World +X heading: %.1f deg from magnetic north (ODOMETRY is rotated by it)\n",
           (double)BS_WORLD_HEADING_DEG);
    printf("Legend: ANG S<sensor> BS<id> h=horiz v=vert [deg]; "
           "P,<sensor>,x,y,z [m]; C,<n>,cx,cy,cz [m]\n");

    /* ② Compute-side init (no sensor I/O here — that lives on core 1) */
    angle_decoder_init(g_angles, CAL);

    /* ③ Launch capture core without blocking the USB diagnostic loop. */
    multicore_launch_core1(core1_entry);
    uint64_t last_debug_us = to_us_since_boot(get_absolute_time());
    printf("Capture core launched.\n");
    stdio_flush();

    /* ④ Compute loop */
    uint64_t last_print_us = 0;
    float    last_cx = 0.0f, last_cy = 0.0f, last_cz = 0.0f;
    float    last_yaw = 0.0f, last_yaw_var = 0.0f;   /* world, CCW from +X [rad] */
    uint64_t last_yaw_us = 0;
    uint64_t jump_since_us = 0;      /* first solve of a centre jump > JUMP_GATE_M, 0 = none */
    uint64_t last_meas_us = 0;       /* capture time the accepted centre refers to (ODOMETRY stamp) */
    uint64_t last_odom_us = 0;       /* when the last ODOMETRY was sent */
    uint64_t sent_meas_us = 0;       /* the stamp it carried */
    uint32_t sent_pairs = 0;         /* decoded angle pairs (all stations) when it was sent */
    float    last_sensor_xyz[NUM_SENSORS][3] = {{0.0f}};
    bool     last_sensor_valid[NUM_SENSORS] = {false};
    uint64_t last_sensor_update_us[NUM_SENSORS] = {0};
    uint64_t last_sensor_log_us[NUM_SENSORS] = {0};

    while (true) {
        uint64_t now_us = to_us_since_boot(get_absolute_time());

        if (now_us - last_debug_us >= 1000000ULL) {
            /* Decoder health, once a second: angle pairs decoded per station in the last second
             * (all sensors). ~50 per sensor per station is a full rate; a station far below
             * the others is hard to decode (blocked, too far, or core 1 overloaded). */
            static uint32_t last_pairs[NUM_BS], last_unpaired[NUM_BS];
            printf("STAT,pairs/s");
            for (int b = 0; b < NUM_BS; b++) {
                uint32_t pairs = angle_decoder_pairs(b);
                printf(",%s=%lu", BS_NAME[b], (unsigned long)(pairs - last_pairs[b]));
                last_pairs[b] = pairs;
            }
            printf(",unpaired");
            for (int b = 0; b < NUM_BS; b++) {
                uint32_t unpaired = angle_decoder_unpaired(b);
                printf(",%s=%lu", BS_NAME[b], (unsigned long)(unpaired - last_unpaired[b]));
                last_unpaired[b] = unpaired;
            }
            printf(",rx_lost=%lu\n", (unsigned long)mavlink_rx_dropped());
#ifndef SYNTHETIC_CAPTURE
            /* Receive health per sensor in the last second: light pulses captured, decoded,
             * of which with 1-2 corrected bits, no polynomial, LFSR search failed, lost (core 1
             * too slow), and the TS4231 configuration read back at boot. */
            static db_lh2_stats_t last_rx[NUM_SENSORS];
            printf("RX,cap/dec/fix/nopoly/lfsr/lost");
            for (int s = 0; s < NUM_SENSORS; s++) {
                db_lh2_stats_t rx;
                db_lh2_get_stats((uint8_t)s, &rx);
                printf(",S%d=%lu/%lu/%lu/%lu/%lu/%lu", s,
                       (unsigned long)(rx.captures - last_rx[s].captures),
                       (unsigned long)(rx.decoded - last_rx[s].decoded),
                       (unsigned long)(rx.corrected - last_rx[s].corrected),
                       (unsigned long)(rx.no_poly - last_rx[s].no_poly),
                       (unsigned long)(rx.lfsr_fail - last_rx[s].lfsr_fail),
                       (unsigned long)(rx.overflows - last_rx[s].overflows));
                last_rx[s] = rx;
            }
            printf(",cfg");
            for (int s = 0; s < NUM_SENSORS; s++) {
                uint16_t cfg = db_lh2_config_readback((uint8_t)s);
                if (cfg == 0x392B) printf(",S%d=ok", s);
                else printf(",S%d=0x%04X", s, cfg);
            }
            printf("\n");
#endif
            stdio_flush();
            last_debug_us = now_us;
        }

        /* USB console commands: 'o' starts the OOTX bit stream used by
         * utils/calibration/lh2_ootx.py, 'x' stops it. */
        int console_char = getchar_timeout_us(0);
        if (console_char == 'o') {
            angle_decoder_set_ootx_stream(true);
        } else if (console_char == 'x') {
            angle_decoder_set_ootx_stream(false);
        }

        /* Drain UART RX every iteration — EKF_STATUS_REPORT arrives at 1 Hz
         * (34-byte frames) so calling this at full loop rate keeps the FIFO empty. */
        mavlink_rx_update();

        /* Decode whatever core 1 has produced since last pass. */
        if (g_capture_ready) {
            angle_decoder_update(g_lh2, g_angles, CAL, now_us);
#ifndef SYNTHETIC_CAPTURE
            /* Apply a station's factory calibration as soon as it is decoded from its light. */
            for (int b = 0; b < NUM_BS; b++) {
                lh2_plane_cal_t planes[2];
                uint32_t uid;
                if (ootx_take_update(b, planes, &uid)) {
                    CAL[b].plane[0] = planes[0];
                    CAL[b].plane[1] = planes[1];
                    printf("OOTX,%s,uid=%08lX,applied\n", BS_NAME[b], (unsigned long)uid);
                }
            }
#endif
        }

        /* ── Event-driven: solve + cache centroid, only when fresh data exists ── */
        if (g_capture_ready) {
            lh2_point3d_t pts[NUM_SENSORS];
            int n = solve3d_calib_run(BS_POSES, g_angles, now_us, pts);
            for (int s = 0; s < NUM_SENSORS; s++) last_sensor_valid[s] = false;

            if (n > 0) {
                float acc_x[NUM_SENSORS]={0}, acc_y[NUM_SENSORS]={0}, acc_z[NUM_SENSORS]={0};
                int   cnt[NUM_SENSORS]={0};
                for (int i = 0; i < n; i++) {
                    int s = pts[i].sensor_id;
                    if (s >= 0 && s < NUM_SENSORS) {
                        acc_x[s] += pts[i].xyz[0];
                        acc_y[s] += pts[i].xyz[1];
                        acc_z[s] += pts[i].xyz[2];
                        cnt[s]++;
                    }
                }
                float xyz[NUM_SENSORS][3];
                bool  ok[NUM_SENSORS];
                for (int s = 0; s < NUM_SENSORS; s++) {
                    ok[s] = cnt[s] > 0;
                    if (!ok[s]) continue;
                    xyz[s][0] = acc_x[s] / cnt[s];
                    xyz[s][1] = acc_y[s] / cnt[s];
                    xyz[s][2] = acc_z[s] / cnt[s];
                }
                float sx = 0.0f, sy = 0.0f, sz = 0.0f;
                int   na = _board_check(xyz, ok);
                for (int s = 0; s < NUM_SENSORS; s++) {
                    if (!ok[s]) continue;
                    sx += xyz[s][0]; sy += xyz[s][1]; sz += xyz[s][2];
                }
                bool accept = na > 0;
                if (accept && (last_cx != 0.0f || last_cy != 0.0f || last_cz != 0.0f)) {
                    const float dx = sx / na - last_cx, dy = sy / na - last_cy, dz = sz / na - last_cz;
                    if (dx * dx + dy * dy + dz * dz > JUMP_GATE_M * JUMP_GATE_M) {
                        if (jump_since_us == 0) jump_since_us = now_us;
                        accept = now_us - jump_since_us >= JUMP_PERSIST_US;  /* it lasts: real */
                    }
                }
                if (accept) {
                    jump_since_us = 0;
                    /* The solver carried every ray to now_us (capture clock): that is the moment
                     * this position describes, and the ODOMETRY stamp. (It was the mean capture
                     * time of all rays up to 500 ms old: it lagged and jumped back and forth.) */
                    last_meas_us = now_us;
                    for (int s = 0; s < NUM_SENSORS; s++) {
                        if (!ok[s]) continue;
                        for (int k = 0; k < 3; k++) last_sensor_xyz[s][k] = xyz[s][k];
                        last_sensor_valid[s] = true;
                        last_sensor_update_us[s] = now_us;
                    }
                    last_cx = sx / na;
                    last_cy = sy / na;
                    last_cz = sz / na;
                }
                float yaw, yaw_var;
                if (accept && _board_yaw(last_sensor_xyz, last_sensor_valid, &yaw, &yaw_var)) {
                    last_yaw = yaw;
                    last_yaw_var = yaw_var;
                    last_yaw_us = now_us;
                }
            }
        }

        /* ── 30 Hz: ODOMETRY, only with a position solved since new sweeps arrived ── */
        uint32_t pairs_now = 0;
        for (int b = 0; b < NUM_BS; b++) pairs_now += angle_decoder_pairs(b);
        if (last_yaw_us != 0 && (last_cx != 0.0f || last_cy != 0.0f || last_cz != 0.0f) &&
            now_us - last_odom_us >= ODOM_INTERVAL_US && pairs_now != sent_pairs &&
            last_meas_us > sent_meas_us && last_meas_us - sent_meas_us >= ODOM_MIN_GAP_US) {
            /* World frame is right-handed Z-up (X -> the 1 m mark, Y left); LOCAL_FRD is
             * X forward, Y right, Z down: flip Y and Z. Flipping Z alone mirrors the
             * lateral axis and position hold runs away sideways. With compass yaw ArduPilot
             * reads these as north / east, so the frame is turned by the heading of +X
             * (BS_WORLD_HEADING_DEG); a wrong heading makes position hold circle the spot. */
            const float fwd = last_cx, right = -last_cy;
            /* Yaw goes the same way: clockwise (FRD) = -world, then + the +X heading. A yaw
             * older than YAW_STALE_US is still sent, flagged as unknown by a large variance. */
            const float yaw_ned = -last_yaw + BS_WORLD_HEADING_DEG * (float)M_PI / 180.0f;
            const bool  yaw_fresh = now_us - last_yaw_us < YAW_STALE_US;
            /* Stamp in the Pico's own clock, never TIMESYNC-corrected: ArduPilot's jitter correction
             * (JitterCorrection, max lag 500 ms) learns the clock offset by itself, and a
             * TIMESYNC lock arriving mid-flight would move the stamps ~6 s back at once, which
             * it reads as samples 500 ms old for ~100 samples (flight log 2026-10-23: TIMESYNC
             * never locked and the steady offset was harmless, lag 55-70 ms). */
            mavlink_send_odometry(last_meas_us,
                                  fwd * s_heading_cos - right * s_heading_sin,
                                  fwd * s_heading_sin + right * s_heading_cos, -last_cz,
                                  yaw_ned, yaw_fresh ? last_yaw_var : YAW_VAR_UNKNOWN);
            last_odom_us = now_us;
            sent_meas_us = last_meas_us;
            sent_pairs = pairs_now;
        }

        /* ── 10 Hz: TUNNEL, OOTX, EKF home-set (once) + diagnostic prints ───── */
        if (now_us - last_print_us < PRINT_INTERVAL_US) {
            continue;
        }
        last_print_us = now_us;

        for (int s = 0; s < NUM_SENSORS; s++) {
            if (!last_sensor_valid[s] || last_sensor_update_us[s] == last_sensor_log_us[s] ||
                now_us - last_sensor_update_us[s] > FRESHNESS_US) continue;
            printf("Q,%llu,%d,%.5f,%.5f,%.5f\n",
                   (unsigned long long)last_sensor_update_us[s], s,
                   (double)last_sensor_xyz[s][0],
                   (double)last_sensor_xyz[s][1],
                   (double)last_sensor_xyz[s][2]);
            last_sensor_log_us[s] = last_sensor_update_us[s];
        }

        uint16_t angle_valid_mask = 0u;
        float raw_angles[NUM_SENSORS][NUM_BS][2] = {{{0.0f}}};
        uint8_t angle_age_ms[NUM_SENSORS][NUM_BS];
        for (int s = 0; s < NUM_SENSORS; s++) {
            for (int bs = 0; bs < NUM_BS; bs++) {
            angle_age_ms[s][bs] = UINT8_MAX;
                if (!g_angles[s][bs].valid ||
                    (now_us - g_angles[s][bs].last_update_us) > FRESHNESS_US) {
                    continue;
                }
                angle_valid_mask |= (uint16_t)(1u << (s * NUM_BS + bs));
                raw_angles[s][bs][0] = g_angles[s][bs].raw_horiz;
                raw_angles[s][bs][1] = g_angles[s][bs].raw_vert;
                uint64_t age_ms = (now_us - g_angles[s][bs].last_update_us) / 1000ULL;
                angle_age_ms[s][bs] = (age_ms > UINT8_MAX) ? UINT8_MAX : (uint8_t)age_ms;
            }
        }
        if (angle_valid_mask != 0u) {
            mavlink_send_lh2_angles(mavlink_timesync_corrected_us(now_us),
                                    raw_angles, angle_age_ms, angle_valid_mask);
        }

        /* Factory-calibration status to the ground station: one station per 0.5 s (each every 2 s),
         * only for stations whose OOTX bits are arriving. */
        {
            static uint64_t last_ootx_us = 0;
            static int ootx_next = 0;
            if (now_us - last_ootx_us >= 500000ULL) {
                last_ootx_us = now_us;
                const ootx_station_t *o = ootx_station(ootx_next);
                if (o && o->bits > 0) mavlink_send_lh2_ootx(ootx_next, o);
                ootx_next = (ootx_next + 1) % NUM_BS;
            }
        }

        /* Yaw for the USB console (ODOMETRY itself goes out at 30 Hz above). */
        if (last_cx != 0.0f || last_cy != 0.0f || last_cz != 0.0f) {
            const bool yaw_fresh = last_yaw_us != 0 && now_us - last_yaw_us < YAW_STALE_US;
            printf("YAW,%.1f,%d\n", (double)_rad2deg(last_yaw), yaw_fresh ? 1 : 0);
        }

        /* Send DO_SET_HOME exactly once — the first time EKF reports healthy.
         * g_home_set latches true so this never fires again, even if EKF
         * later cycles healthy → unhealthy → healthy. */
        if (!g_home_set && mavlink_is_ekf_healthy()) {
            mavlink_send_do_set_home();
            g_home_set = true;
            printf("EKF healthy — home set\n");
        }

        /* Diagnostic angle output for every detected lighthouse. */
        for (int s = 0; s < NUM_SENSORS; s++) {
            if (!angle_decoder_is_fresh(g_angles, s, now_us)) continue;

            for (int bs = 0; bs < NUM_BS; bs++) {
                if (!angle_decoder_bs_fresh(g_angles, s, bs, now_us)) continue;
                float horiz = _rad2deg(g_angles[s][bs].ema_horiz);
                float vert = _rad2deg(g_angles[s][bs].ema_vert);

                printf("A,%d,%d,%.2f,%.2f\n", s, bs,
                       (double)horiz, (double)vert);
                printf("ANG S%d | %s h=%+7.2f v=%+7.2f deg\n",
                       s, BS_NAME[bs], (double)horiz, (double)vert);
            }
        }

        if (last_cx != 0.0f || last_cy != 0.0f || last_cz != 0.0f) {
            printf("C,%.4f,%.4f,%.4f\n",
                   (double)last_cx, (double)last_cy, (double)last_cz);
        }
    }

    return 0;   /* unreachable */
}
